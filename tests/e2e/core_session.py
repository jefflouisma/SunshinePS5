class Host:
    def __init__(self, binary, address, root, state):
        self.root = root
        self.events = queue.Queue()
        self.history = []
        self.errors = (root / "host.stderr").open("a")
        self.log = (root / "host.jsonl").open("a")
        self.process = subprocess.Popen(
            [
                str(binary),
                address,
                str(state),
                str(root / "video.h264"),
                str(root / "audio.opus"),
                str(root / "metrics.ndjson"),
            ],
            stdin=subprocess.PIPE,
            stdout=subprocess.PIPE,
            stderr=self.errors,
            text=True,
            bufsize=1,
        )
        self.reader = threading.Thread(target=self._read, daemon=True)
        self.reader.start()
        self.event("ready")

    def _read(self):
        for line in self.process.stdout:
            self.log.write(line)
            self.log.flush()
            try:
                item = json.loads(line)
                self.history.append(item)
                self.events.put(item)
            except json.JSONDecodeError:
                self.events.put({"event": "invalid-json", "raw": line})
        self.events.put({"event": "exited", "exit": self.process.poll()})

    def event(self, name, timeout=15):
        deadline = time.monotonic() + timeout
        while time.monotonic() < deadline:
            item = self.events.get(timeout=max(0.01, deadline - time.monotonic()))
            checked(item["event"] != "invalid-json", item)
            checked(
                item["event"] != "exited", f"host exited while awaiting {name}: {item}"
            )
            if item["event"] == name:
                return item
        raise AssertionError(f"missing host event {name}")

    def command(self, value):
        self.process.stdin.write(value + "\n")
        self.process.stdin.flush()

    def status(self):
        self.command("status")
        return self.event("status")

    def end(self, reason, timeout=15):
        result = self.event("ended", timeout)
        checked(result["reason"] == reason, result)
        checked(
            result["clean"] and result["enet_blocks"] == result["enet_exhausted"] == 0,
            result,
        )
        checked(result["input_release_sequence"] > 0, result)
        return result

    def close(self):
        if self.process.poll() is None:
            self.command("stop")
            try:
                self.process.wait(timeout=15)
            except subprocess.TimeoutExpired:
                self.process.kill()
                self.process.wait(timeout=5)
                raise AssertionError("host did not cleanly stop") from None
        self.reader.join(timeout=5)
        self.log.close()
        self.errors.close()
        checked(self.process.returncode == 0, (self.root / "host.stderr").read_text())
        checked(
            not (self.root / "host.stderr").read_text(), "host/sanitizer diagnostics"
        )


def pair(host, client, config, address):
    pin = f"{secrets.randbelow(10000):04d}"
    process = subprocess.Popen(
        [
            str(client),
            "--config-dir",
            str(config),
            "pair",
            "--host",
            address,
            "--pin",
            pin,
        ],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
    )
    try:
        host.event("pair_pending")
        host.command("pin " + pin)
        checked(host.event("pin_submitted")["accepted"], "PIN refused")
        output, error = process.communicate(timeout=20)
        checked(process.returncode == 0, (output + error).replace(pin, "[redacted]"))
        checked(host.status()["paired"] == 1, "pairing was not persisted")
    finally:
        if process.poll() is None:
            process.kill()
            process.wait(timeout=5)


def wrong_pin(host, client, config, address):
    """Official-client abort: the client detects the wrong PIN before step 4.

    Moonlight checks the host's challenge hash itself (client check B) and sends
    GET /unpair instead of its final proof (protocol-notes.md 13.5). The host must
    count one failed PIN and accept an immediate retry instead of staying pending.
    """
    pin = f"{secrets.randbelow(10000):04d}"
    entered = f"{(int(pin) + 1) % 10000:04d}"
    before = host.status()
    process = subprocess.Popen(
        [
            str(client),
            "--config-dir",
            str(config),
            "pair",
            "--host",
            address,
            "--pin",
            pin,
        ],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
    )
    try:
        host.event("pair_pending")
        host.command("pin " + entered)
        checked(
            host.event("pin_submitted")["accepted"], "wrong PIN refused before proof"
        )
        output, error = process.communicate(timeout=20)
        text = (
            (output + error).replace(pin, "[redacted]").replace(entered, "[redacted]")
        )
        checked(process.returncode != 0, "a wrong PIN paired")
        checked("PIN entered on the host was wrong" in text, text)
        after = host.status()
        checked(not after["pairing_pending"], "the aborted request stayed pending")
        checked(
            after["pairing_failures"] == before["pairing_failures"] + 1,
            "the wrong PIN was not counted exactly once",
        )
        checked(after["paired"] == before["paired"], "a wrong PIN changed the registry")
    finally:
        if process.poll() is None:
            process.kill()
            process.wait(timeout=5)
    return {
        "client_rejected": True,
        "pending_after_abort": False,
        "failures_counted": 1,
    }


def client_command(client, config, address, command):
    return execute(
        [str(client), "--config-dir", str(config), command, "--host", address]
    )


def run_client(client, config, address, directory, label, duration=None):
    scenario = json.loads((ROOT / "tests/scenarios/core-fake.json").read_text())
    scenario["host"] = address
    scenario["id"] = "core-fake-" + label
    scenario["output_dir"] = label
    if duration is not None:
        scenario["duration_seconds"] = duration
    path = directory / (label + ".scenario.json")
    report = directory / (label + ".report.json")
    path.write_text(json.dumps(scenario, indent=2) + "\n")
    log = (directory / (label + ".client.log")).open("w")
    process = subprocess.Popen(
        [
            str(client),
            "--config-dir",
            str(config),
            "run",
            "--scenario",
            str(path),
            "--report",
            str(report),
        ],
        cwd=directory,
        stdout=log,
        stderr=log,
        text=True,
    )
    return process, log, report


def finish_client(process, log, report):
    try:
        checked(
            process.wait(timeout=20) == 2,
            "fake acceptance report must remain Incomplete",
        )
    finally:
        log.close()
        if process.poll() is None:
            process.kill()
            process.wait(timeout=5)
    value = json.loads(report.read_text())
    checked(value["overall_status"] == "Incomplete", value["overall_status"])
    expected = json.loads((ROOT / "tests/scenarios/core-fake.json").read_text())[
        "required_criteria"
    ]
    checked(
        {item["id"] for item in value["criteria"]} == set(expected["ids"]),
        "criterion lost",
    )
    return value


def media_evidence(root, label):
    directory = root / label
    summary = json.loads((directory / "receipt-summary.json").read_text())
    video, audio = summary["video"], summary["audio"]
    checked(video["frames_complete"] >= 5 and video["frames_incomplete"] == 0, video)
    checked(audio["decoded_packets"] >= 10 and audio["decode_failures"] == 0, audio)
    checked(all(count > 0 for count in audio["nonzero_samples_per_channel"]), audio)
    encoded = (directory / "elementary.bin").read_bytes()
    fixture = (root / "video.h264").read_bytes()
    checked(
        encoded == fixture * video["frames_complete"], "encoded fixture bytes changed"
    )
    probe = execute(
        [
            "ffprobe",
            "-v",
            "error",
            "-f",
            "h264",
            "-show_entries",
            "stream=width,height,codec_name",
            "-of",
            "json",
            str(directory / "elementary.bin"),
        ]
    )
    checked(probe.returncode == 0, probe.stderr)
    stream = json.loads(probe.stdout)["streams"][0]
    checked(
        stream["codec_name"] == "h264"
        and stream["width"] == 1280
        and stream["height"] == 720,
        stream,
    )
    decoded = execute(
        [
            "ffmpeg",
            "-v",
            "error",
            "-f",
            "h264",
            "-i",
            str(directory / "elementary.bin"),
            "-frames:v",
            "3",
            "-f",
            "null",
            "-",
        ]
    )
    checked(decoded.returncode == 0 and not decoded.stderr, decoded.stderr)
    return {
        "video_frames": video["frames_complete"],
        "audio_packets": audio["decoded_packets"],
    }


def scenario_suite(args, root, address, private):
    state = private / "host"
    state.mkdir(mode=0o700)
    config = private / "client"
    host = Host(args.host_bin, address, root, state)
    results = {}
    active = None
    try:
        checked(
            client_command(
                args.client_bin, private / "unpaired", address, "apps"
            ).returncode
            != 0,
            "unpaired device got apps",
        )
        results["wrong_pin"] = wrong_pin(host, args.client_bin, config, address)
        # The immediate correct-PIN retry is a new request, never a 409 conflict.
        pair(host, args.client_bin, config, address)
        for _ in range(2):
            apps = client_command(args.client_bin, config, address, "apps")
            checked(apps.returncode == 0 and "PS5" in apps.stdout, apps.stderr)
        active, log, report = run_client(
            args.client_bin, config, address, root, "normal"
        )
        host.event("reserved")
        host.event("streaming")
        time.sleep(0.35)
        before = host.status()
        host.command("pause-media")
        checked(host.event("media_pause")["paused"], "media did not pause")
        time.sleep(0.7)
        after = host.status()
        checked(after["inputs"] > before["inputs"], "input stalled behind media")
        checked(
            after["video_frames"] <= before["video_frames"] + 1,
            "media did not stay paused",
        )
        host.command("resume-media")
        checked(not host.event("media_pause")["paused"], "media did not resume")
        finish_client(active, log, report)
        active = None
        ended = host.end(0)
        checked(ended["inputs"] >= 6 and ended["media_closes"] == 3, ended)
        observed = host.event("input_observations")
        checked(
            observed["buttons_seen"] & 0x1000
            and observed["axes_seen"]
            and observed["triggers_seen"],
            observed,
        )
        results["normal"] = media_evidence(root, "normal")
        results["independent_input"] = {"before": before, "while_media_paused": after}
        reserved = [item for item in host.history if item["event"] == "reserved"][-1]
        checked(
            reserved["requested_kbps"] == 25000 and reserved["chosen_kbps"] == 20000,
            reserved,
        )
        active, log, report = run_client(
            args.client_bin, config, address, root, "revocation", 8
        )
        host.event("streaming")
        time.sleep(1.1)
        checked(host.status()["inputs"] >= 4, "no held input before revoke")
        began = time.monotonic()
        host.command("revoke")
        ended = host.end(2, 2)
        host.event("revoked", 2)
        revoke_seconds = time.monotonic() - began
        checked(revoke_seconds < 2, "revocation deadline")
        ended["revocation_seconds"] = revoke_seconds
        finish_client(active, log, report)
        active = None
        checked(
            client_command(args.client_bin, config, address, "apps").returncode != 0,
            "revoked client still has access",
        )
        results["revocation"] = ended
        # Re-pair using the same client identity; a new lease must be acquired.
        pair(host, args.client_bin, config, address)
        host.command("fail audio-open")
        host.event("failure_armed")
        active, log, report = run_client(
            args.client_bin, config, address, root, "partial-start"
        )
        ended = host.end(5)
        finish_client(active, log, report)
        active = None
        checked(ended["clean"] and ended["media_closes"] == 2, ended)
        checked(
            client_command(args.client_bin, config, address, "apps").returncode == 0,
            "partial start prevented reuse",
        )
        results["partial_start"] = ended
        active, log, report = run_client(
            args.client_bin, config, address, root, "loss", 20
        )
        host.event("streaming")
        time.sleep(1.1)
        checked(host.status()["inputs"] >= 4, "loss case had no controller input")
        lost = time.monotonic()
        active.kill()
        active.wait(timeout=5)
        active = None
        log.close()
        ended = host.end(1, 11)
        loss_seconds = time.monotonic() - lost
        checked(
            loss_seconds <= 10,
            "silent client loss exceeded ten seconds after process death",
        )
        ended["seconds_after_process_death"] = loss_seconds
        checked(ended["media_closes"] == 3, ended)
        results["silent_loss"] = ended
        # A killed client leaves an unfinished initial journal, never acceptance.
        checked(
            json.loads(report.read_text())["overall_status"] == "Incomplete",
            "killed report passed",
        )
        active, log, report = run_client(
            args.client_bin, config, address, root, "reuse"
        )
        host.event("streaming")
        finish_client(active, log, report)
        active = None
        results["reuse"] = host.end(0)
        results["reuse_media"] = media_evidence(root, "reuse")
        host.close()
        # Restart from actual POSIX persisted identity/registry; then revoke idle
        # and restart again to prove removal survives a process boundary.
        host = Host(args.host_bin, address, root, state)
        checked(host.status()["paired"] == 1, "pairing did not survive restart")
        checked(
            client_command(args.client_bin, config, address, "apps").returncode == 0,
            "stored identity failed mutual TLS after restart",
        )
        # Internal revocation targets the certificate from the previous launch;
        # perform another run so this process has an explicit launch identity.
        active, log, report = run_client(
            args.client_bin, config, address, root, "restart"
        )
        host.event("streaming")
        finish_client(active, log, report)
        active = None
        host.end(0)
        host.command("revoke")
        host.event("revoked")
        host.close()
        host = Host(args.host_bin, address, root, state)
        checked(host.status()["paired"] == 0, "revocation did not persist")
        checked(
            client_command(args.client_bin, config, address, "apps").returncode != 0,
            "revocation forgotten after restart",
        )
        results["persistence"] = True
    finally:
        if active is not None and active.poll() is None:
            active.kill()
            active.wait(timeout=5)
        host.close()
    return results


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--host-bin", type=Path, required=True)
    parser.add_argument("--client-bin", type=Path, required=True)
    parser.add_argument("--output-root", type=Path, required=True)
    parser.add_argument("--bind")
    args = parser.parse_args()
    args.host_bin = args.host_bin.resolve(strict=True)
    args.client_bin = args.client_bin.resolve(strict=True)
    args.output_root.mkdir(parents=True, exist_ok=True)
    root = args.output_root.resolve()
    checked(
        not (root / "video.h264").exists(), "use a fresh task-local output directory"
    )
    address = private_address(args.bind) if args.bind else local_address()
    # Keep credentials isolated and remove them even on a failed test run.
    private = root / "private"
    private.mkdir(mode=0o700)
    summary = {
        "synthetic": True,
        "hardware_evidence": False,
        "acceptance_status": "Incomplete",
    }
    try:
        fixtures(root)
        summary["cases"] = scenario_suite(args, root, address, private)
        summary["software_integration"] = "Pass"
    except Exception as error:
        summary["software_integration"] = "Fail"
        summary["failure"] = str(error)
        raise
    finally:
        shutil.rmtree(private)
        (root / "e2e-result.json").write_text(json.dumps(summary, indent=2) + "\n")
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
