"""Real portable-core protocol sessions through the independent Rust CLI.

Run from repo root: python3 tests/e2e/core_session.py
  --host-bin BUILD/tests/sp5_fake_host --client-bin TARGET/debug/moonlight-mcp
  --output-root TASK_SCRATCH [--bind PRIVATE_IPV4]
The host's stdin is a local fixture-control channel, never a phone/web API.
All acceptance reports keep their complete declared criteria and Incomplete status;
passing this software integration suite establishes no PS5/reference-host acceptance.
"""

